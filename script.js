const nodeWidth = 138;
const nodeHeight = 64;
const siblingGap = 34;
const levelGap = 118;
const graphPadding = 52;
let selectedId = familyTree.id;
let zoom = 0.55;
let query = "";

function flattenTree(person, path = []) {
  const nextPath = [...path, person.name];
  return [
    { ...person, tags: person.tags || [], path: nextPath },
    ...(person.children || []).flatMap((child) => flattenTree(child, nextPath)),
  ];
}

function layoutTree(person, depth = 0) {
  const children = (person.children || []).map((child) => layoutTree(child, depth + 1));
  const subtreeWidth = children.length
    ? children.reduce((sum, child) => sum + child.subtreeWidth, 0) + siblingGap * (children.length - 1)
    : nodeWidth;
  let cursor = 0;
  const positionedChildren = children.map((child) => {
    const shifted = shiftTree(child, cursor);
    cursor += child.subtreeWidth + siblingGap;
    return shifted;
  });
  return { ...person, children: positionedChildren, subtreeWidth, x: subtreeWidth / 2, y: depth * levelGap };
}

function shiftTree(person, offsetX) {
  return { ...person, x: person.x + offsetX, children: (person.children || []).map((child) => shiftTree(child, offsetX)) };
}

function getLayoutNodes(person) {
  return [person, ...(person.children || []).flatMap(getLayoutNodes)];
}

function getBranchGroups(person) {
  return [...((person.children || []).length ? [person] : []), ...(person.children || []).flatMap(getBranchGroups)];
}

function getMaxDepth(person) {
  return Math.max(0, ...(person.children || []).map((child) => 1 + getMaxDepth(child)));
}

const people = flattenTree(familyTree);

function selectedPerson() {
  return people.find((person) => person.id === selectedId) || people[0];
}

function matchingIds() {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return new Set();
  return new Set(
    people
      .filter((person) => [person.name, person.subtitle, person.note, ...person.tags, person.path.join(" ")].join(" ").toLowerCase().includes(normalized))
      .map((person) => person.id),
  );
}

function renderDetails() {
  const person = selectedPerson();
  document.getElementById("selected-name").textContent = person.name;
  document.getElementById("selected-subtitle").textContent = person.subtitle || "";
  document.getElementById("selected-note").textContent = person.note || "This name appears in the handwritten chart. More oral history can be added here as it is recovered.";
  document.getElementById("selected-path").textContent = person.path.join(" -> ");
  const tags = document.getElementById("selected-tags");
  tags.innerHTML = "";
  person.tags.forEach((tag) => {
    const span = document.createElement("span");
    span.textContent = tag;
    tags.appendChild(span);
  });
}

function renderGraph() {
  const container = document.getElementById("tree-scroll");
  const raw = layoutTree(familyTree);
  const layout = shiftTree(raw, graphPadding);
  const nodes = getLayoutNodes(layout);
  const groups = getBranchGroups(layout);
  const width = raw.subtreeWidth + graphPadding * 2;
  const height = (getMaxDepth(familyTree) + 1) * levelGap + graphPadding * 2;
  const matches = matchingIds();
  const scaledWidth = Math.round(width * zoom);
  const scaledHeight = Math.round(height * zoom);

  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("class", "family-graph");
  svg.setAttribute("role", "img");
  svg.setAttribute("aria-label", "Connected Joshi Kovadkar family tree");
  svg.setAttribute("width", scaledWidth);
  svg.setAttribute("height", scaledHeight);
  svg.setAttribute("viewBox", `0 0 ${width} ${height}`);

  const rootGroup = document.createElementNS("http://www.w3.org/2000/svg", "g");
  rootGroup.setAttribute("transform", `translate(0 ${graphPadding})`);
  svg.appendChild(rootGroup);

  groups.forEach((parent) => {
    const children = parent.children || [];
    const startX = parent.x;
    const startY = parent.y + nodeHeight;
    const childTopY = children[0] ? children[0].y : startY;
    const branchY = startY + (childTopY - startY) * 0.48;
    const minChildX = Math.min(...children.map((child) => child.x));
    const maxChildX = Math.max(...children.map((child) => child.x));

    addPath(rootGroup, children.length === 1 ? `M ${startX} ${startY} V ${childTopY}` : `M ${startX} ${startY} V ${branchY}`, "tree-link parent-stem");
    if (children.length > 1) {
      addPath(rootGroup, `M ${minChildX} ${branchY} H ${maxChildX}`, "tree-link sibling-bar");
      children.forEach((child) => addPath(rootGroup, `M ${child.x} ${branchY} V ${child.y}`, "tree-link child-stem"));
    }
  });

  nodes.forEach((person) => {
    const foreignObject = document.createElementNS("http://www.w3.org/2000/svg", "foreignObject");
    foreignObject.setAttribute("height", nodeHeight);
    foreignObject.setAttribute("width", nodeWidth);
    foreignObject.setAttribute("x", person.x - nodeWidth / 2);
    foreignObject.setAttribute("y", person.y);

    const button = document.createElement("button");
    button.type = "button";
    button.className = `graph-card ${person.id === selectedId ? "selected" : ""} ${matches.has(person.id) ? "match" : ""}`;
    button.innerHTML = `<span>${escapeHtml(person.name)}</span>${person.subtitle ? `<small>${escapeHtml(person.subtitle)}</small>` : ""}`;
    button.addEventListener("click", () => {
      selectedId = person.id;
      renderDetails();
      renderGraph();
    });
    foreignObject.appendChild(button);
    rootGroup.appendChild(foreignObject);
  });

  container.innerHTML = "";
  container.appendChild(svg);
  document.getElementById("tree-counter").textContent = query ? `${matches.size} matches` : `${people.length} names mapped`;
}

function addPath(parent, d, className) {
  const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
  path.setAttribute("class", className);
  path.setAttribute("d", d);
  parent.appendChild(path);
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (char) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;" })[char]);
}

function setZoom(nextZoom) {
  zoom = Math.min(1.25, Math.max(0.25, Number(nextZoom.toFixed(2))));
  document.getElementById("zoom-slider").value = zoom;
  document.getElementById("zoom-label").textContent = `${Math.round(zoom * 100)}%`;
  renderGraph();
}

document.getElementById("tree-search").addEventListener("input", (event) => {
  query = event.target.value;
  renderGraph();
});
document.getElementById("zoom-out").addEventListener("click", () => setZoom(zoom - 0.1));
document.getElementById("zoom-in").addEventListener("click", () => setZoom(zoom + 0.1));
document.getElementById("zoom-fit").addEventListener("click", () => setZoom(0.3));
document.getElementById("zoom-reset").addEventListener("click", () => setZoom(0.55));
document.getElementById("zoom-slider").addEventListener("input", (event) => setZoom(Number(event.target.value)));

renderDetails();
renderGraph();
